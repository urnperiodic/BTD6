export function getTowerShortName(spec: TowerSpec): string {
  if (spec.shortName) return spec.shortName;
  const cleaned = spec.name
    .replace(' (Water)', '')
    .replace(' (Platform)', '')
    .replace(/^Monkey\s+/i, '')
    .replace(/\s+Monkey$/i, '')
    .trim();
  return cleaned.split(' ')[0] || spec.name;
}

